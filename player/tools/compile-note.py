"""Compile the supplied M/C/c/z SVG contour to NanoVG calls without rasterizing."""
from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]
svg=root/'assets/icons/music-note.svg'
path=re.search(r'<path\s+d="([^"]+)"',svg.read_text()).group(1)
tokens=re.findall(r'[A-Za-z]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?',path)
out=['// Generated by player/tools/compile-note.py from assets/icons/music-note.svg.']
i=0;command=None;x=y=0.
def f(v):return f'{v:.6f}f'
while i<len(tokens):
 if tokens[i].isalpha():command=tokens[i];i+=1
 if command in ('z','Z'):
  out.append('nvgClosePath(vg);');command=None;continue
 count={'M':2,'L':2,'l':2,'C':6,'c':6}[command]
 values=[float(v) for v in tokens[i:i+count]];assert len(values)==count;i+=count
 if command=='M':x,y=values;out.append(f'nvgMoveTo(vg,{f(x)},{f(y)});');command='L'
 elif command in ('L','l'):
  x,y=(values[0]+x,values[1]+y) if command=='l' else values
  out.append(f'nvgLineTo(vg,{f(x)},{f(y)});')
 else:
  if command=='c':values=[v+(x if j%2==0 else y) for j,v in enumerate(values)]
  x,y=values[-2:];out.append('nvgBezierTo(vg,'+','.join(f(v) for v in values)+');')
(root/'src/note_path.inc').write_text('\n'.join(out)+'\n')
